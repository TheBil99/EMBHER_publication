#!/usr/bin/env python3
"""
Build an embher-capture --config YAML from a plain donor-id list.

embher-capture's --sample_ids only accepts a bare argv list, unwieldy for an
800-donor cohort; wrapping it in a --config YAML lets merge_configs() apply it while
every other flag stays on the CLI (CLI values override YAML, and only this file sets
sample_ids, so nothing downstream needs to know this indirection exists).

Built offline and committed under configs/ -- this project's convention is that
pipeline config inputs are never generated by a live Nextflow process.

Usage:
    python make_donors_config.py \
        --donors-txt results/02-expression_data_preparation/gtex/pheno_matrix/Whole_Blood/Whole_Blood_tquantile_int_vnone_g5_p10_r0.9_donors.txt \
        --out workflows/06-extract_embeddings/configs/whole_blood_donors_config.yaml
"""

import argparse
from pathlib import Path


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument('--donors-txt', required=True)
    p.add_argument('--out', required=True)
    return p.parse_args()


def main():
    args = parse_args()

    donors = [line.strip() for line in Path(args.donors_txt).read_text().splitlines() if line.strip()]
    if any(':' in d or '#' in d for d in donors):
        raise SystemExit("a donor id contains a YAML-significant character (':' or '#'); "
                          "hand-rolled emission below assumes plain GTEx-style ids")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    # A flat list of plain donor ids needs no quoting or
    # escaping, so emit it by hand rather than adding a dependency for one line of YAML.
    with open(out_path, 'w') as f:
        f.write('sample_ids:\n')
        for d in donors:
            f.write(f'  - {d}\n')

    print(f"Wrote {len(donors)} donors to {out_path}")


if __name__ == '__main__':
    main()
